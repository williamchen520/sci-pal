-- scipal_core.auth schema
-- Business/identity tables only. No papers / paragraphs / embeddings.
-- Cross-database FKs are intentionally absent; associations are logical IDs.

CREATE SCHEMA IF NOT EXISTS auth;

CREATE TABLE IF NOT EXISTS auth.users (
    user_id text PRIMARY KEY,
    username text NOT NULL UNIQUE,
    email text,
    display_name text,
    password_hash text,
    status text NOT NULL DEFAULT 'active',
    is_admin bigint NOT NULL DEFAULT 0,
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS auth.roles (
    role_id text PRIMARY KEY,
    name text NOT NULL UNIQUE,
    description text NOT NULL DEFAULT '',
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS auth.permissions (
    permission_id text PRIMARY KEY,
    code text NOT NULL UNIQUE,
    description text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS auth.role_permissions (
    role_id text NOT NULL,
    permission_id text NOT NULL,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS auth.user_roles (
    user_id text NOT NULL,
    role_id text NOT NULL,
    workspace_id text NOT NULL DEFAULT '*',
    granted_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    PRIMARY KEY (user_id, role_id, workspace_id)
);

CREATE TABLE IF NOT EXISTS auth.user_configs (
    user_id text NOT NULL,
    config_key text NOT NULL,
    config_value jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    PRIMARY KEY (user_id, config_key)
);

CREATE TABLE IF NOT EXISTS auth.workspaces (
    workspace_id text PRIMARY KEY,
    name text NOT NULL,
    owner_user_id text NOT NULL,
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS auth.memberships (
    workspace_id text NOT NULL,
    user_id text NOT NULL,
    role_id text NOT NULL,
    status text NOT NULL DEFAULT 'active',
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS auth.tenancy_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text,
    actor_user_id text,
    action text NOT NULL,
    target text,
    detail text,
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE INDEX IF NOT EXISTS idx_auth_memberships_user
    ON auth.memberships (user_id, status);
CREATE INDEX IF NOT EXISTS idx_auth_user_roles_user
    ON auth.user_roles (user_id);
CREATE INDEX IF NOT EXISTS idx_auth_audit_created
    ON auth.tenancy_audit (created_at);

