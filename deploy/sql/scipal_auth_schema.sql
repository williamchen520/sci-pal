INSERT INTO auth.role_permissions (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM auth.roles r
JOIN auth.permissions p ON (
    (r.role_id = 'owner')
    OR (r.role_id = 'pi' AND p.code IN ('read_workspace','write_own','read_all','copy'))
    OR (r.role_id = 'member' AND p.code IN ('read_workspace','write_own'))
    OR (r.role_id = 'viewer' AND p.code = 'read_workspace')
)
ON CONFLICT DO NOTHING;
