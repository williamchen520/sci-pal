"""PG-backed brief and HTML report (G3.10e4e)."""

from __future__ import annotations

import html
from typing import Dict, List

from services.db.pg_pool import pg_connection
from services.review import pg_systematic, prisma_svg, risk_of_bias, rob_svg


def _rob_rows(project_id: str) -> List[Dict]:
    pg = pg_connection()
    try:
        rows = pg.execute(
            "SELECT paper_id, domain, judgement, support FROM risk_of_bias "
            "WHERE project_id = %s ORDER BY paper_id, domain",
            (project_id,),
        ).fetchall()
        return [dict(row) for row in rows]
    finally:
        pg.close()


def _cell(value: str, limit: int = 80) -> str:
    text = (value or "").replace("|", "/").replace("\n", " ").strip()
    return text[:limit]


def build_brief(project_id: str) -> str:
    project = pg_systematic.get_project(project_id)
    if not project:
        raise KeyError("project not found")
    counts = pg_systematic.prisma(project_id)
    evidence = pg_systematic.list_evidence(project_id)
    rob_rows = _rob_rows(project_id)
    by_paper: Dict[str, List[Dict]] = {}
    for row in rob_rows:
        by_paper.setdefault(row["paper_id"], []).append(row)

    lines = [f"# {project.get('name') or project_id}", ""]
    lines.append(f"- 项目：`{project_id}`")
    lines.append(f"- 领域：{project.get('field_text') or '（未填写）'}")
    lines.append("")
    lines.append("## PICO")
    pico = project.get("pico") or {}
    for key in ("population", "intervention", "comparator", "outcome"):
        lines.append(f"- **{key}**: {pico.get(key) or '（未填写）'}")
    lines.append("")
    lines.append("## PRISMA")
    lines.append("| 指标 | 数量 |")
    lines.append("|---|---|")
    for key in ("identified", "screened", "included", "excluded", "pending"):
        lines.append(f"| {key} | {counts.get(key, 0)} |")
    lines.append("")
    lines.append("## 证据表")
    if evidence:
        lines.append("| paper | design | sample | intervention | comparator | effect |")
        lines.append("|---|---|---|---|---|---|")
        for row in evidence:
            lines.append(
                "| {paper} | {design} | {sample} | {intervention} | {comparator} | {effect} |".format(
                    paper=_cell(row.get("paper_id"), 40),
                    design=_cell(row.get("design"), 24),
                    sample=_cell(row.get("sample_size"), 16),
                    intervention=_cell(row.get("intervention"), 40),
                    comparator=_cell(row.get("comparator"), 40),
                    effect=_cell(row.get("effect"), 24),
                )
            )
    else:
        lines.append("（暂无证据行，先运行 `/evidence` 抽取）")
    lines.append("")
    lines.append("## 风险偏倚")
    if by_paper:
        lines.append("| paper | overall |")
        lines.append("|---|---|")
        for paper, rows in by_paper.items():
            lines.append(f"| {_cell(paper, 40)} | {risk_of_bias.overall(rows)} |")
    else:
        lines.append("（暂无评估，先运行 `/risk-of-bias`）")
    lines.append("")
    lines.append("---")
    lines.append("Generated by SciPal systematic review")
    return "\n".join(lines)


def _cell_html(value: str) -> str:
    return html.escape(str(value or ""))


def render_html(project_id: str) -> str:
    project = pg_systematic.get_project(project_id)
    if not project:
        raise KeyError("project not found")
    counts = pg_systematic.prisma(project_id)
    evidence = pg_systematic.list_evidence(project_id)
    rob_rows = _rob_rows(project_id)
    pico = project.get("pico") or {}

    rows_html = "".join(
        "<tr>"
        f"<td>{_cell_html(row.get('paper_id'))}</td>"
        f"<td>{_cell_html(row.get('design'))}</td>"
        f"<td>{_cell_html(row.get('sample_size'))}</td>"
        f"<td>{_cell_html(row.get('intervention'))}</td>"
        f"<td>{_cell_html(row.get('comparator'))}</td>"
        f"<td>{_cell_html(row.get('effect'))}</td>"
        "</tr>"
        for row in evidence
    )
    evidence_table = (
        "<table><thead><tr><th>Paper</th><th>Design</th><th>Sample</th>"
        "<th>Intervention</th><th>Comparator</th><th>Effect</th></tr></thead>"
        f"<tbody>{rows_html}</tbody></table>"
        if evidence
        else "<p>暂无证据行。</p>"
    )
    by_paper: Dict[str, List[Dict]] = {}
    for row in rob_rows:
        by_paper.setdefault(row["paper_id"], []).append(row)
    rob_table = (
        "<table><thead><tr><th>Paper</th><th>Overall</th></tr></thead><tbody>"
        + "".join(
            f"<tr><td>{_cell_html(paper)}</td><td>{_cell_html(risk_of_bias.overall(items))}</td></tr>"
            for paper, items in by_paper.items()
        )
        + "</tbody></table>"
        if by_paper
        else "<p>暂无风险评估。</p>"
    )
    prisma_counts = "".join(
        f"<li><b>{_cell_html(key)}</b>: {counts.get(key, 0)}</li>"
        for key in ("identified", "screened", "included", "excluded", "pending")
    )
    pico_html = "".join(
        f"<li><b>{_cell_html(key)}</b>: {_cell_html(pico.get(key) or '未填写')}</li>"
        for key in ("population", "intervention", "comparator", "outcome")
    )
    return f"""<!doctype html>
<html lang="zh-CN">
<head><meta charset="utf-8"><title>{_cell_html(project.get('name'))}</title>
<style>
body {{ font-family: -apple-system, "Microsoft YaHei", sans-serif; margin: 32px auto; max-width: 960px; color: #0f172a; }}
h1 {{ border-bottom: 3px solid #0ea5e9; padding-bottom: 8px; }}
h2 {{ margin-top: 28px; color: #0c4a6e; }}
table {{ border-collapse: collapse; width: 100%; font-size: 13px; }}
th, td {{ border: 1px solid #cbd5e1; padding: 6px 8px; text-align: left; vertical-align: top; }}
th {{ background: #f1f5f9; }}
.meta {{ color: #475569; }}
svg {{ max-width: 100%; height: auto; margin: 12px 0; }}
</style></head>
<body>
<h1>{_cell_html(project.get('name'))}</h1>
<p class="meta">项目 {_cell_html(project_id)} · 领域：{_cell_html(project.get('field_text'))}</p>
<h2>PICO</h2><ul>{pico_html}</ul>
<h2>PRISMA</h2><ul>{prisma_counts}</ul>
{prisma_svg.render(project.get('name') or project_id, counts)}
<h2>Evidence table</h2>{evidence_table}
<h2>Risk of bias</h2>{rob_table}
{rob_svg.render(rob_rows)}
<hr><p class="meta">Generated by SciPal systematic review</p>
</body></html>
"""
