"""Render a simple PRISMA-style flow diagram as SVG."""

from __future__ import annotations

from html import escape
from typing import Dict

WIDTH = 760
HEIGHT = 560


def _box(x: int, y: int, w: int, h: int, text: str) -> str:
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" '
        'fill="#0f1a2e" stroke="#38bdf8" stroke-width="2"/>'
        f'<text x="{x + w / 2}" y="{y + h / 2}" fill="#e2e8f0" font-size="16" '
        f'font-family="Microsoft YaHei, sans-serif" text-anchor="middle" '
        f'dominant-baseline="middle">{escape(text)}</text>'
    )


def _arrow(x1: int, y1: int, x2: int, y2: int) -> str:
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="#64748b" '
        'stroke-width="2" marker-end="url(#arrow)"/>'
    )


def render(title: str, counts: Dict[str, int]) -> str:
    identified = int(counts.get("identified", 0))
    screened = int(counts.get("screened", 0))
    included = int(counts.get("included", 0))
    excluded = int(counts.get("excluded", 0))
    pending = int(counts.get("pending", 0))

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" '
        'viewBox="0 0 760 560">',
        "<defs><marker id=\"arrow\" markerWidth=\"10\" markerHeight=\"10\" refX=\"9\" "
        "refY=\"3\" orient=\"auto\"><path d=\"M0,0 L0,6 L9,3 z\" fill=\"#64748b\"/></marker></defs>",
        '<rect width="760" height="560" fill="#0b1020"/>',
        f'<text x="30" y="42" fill="#f5c542" font-size="22" font-family="Microsoft YaHei, sans-serif">'
        f'PRISMA · {escape(title)}</text>',
        _box(230, 80, 300, 70, f"Records identified: {identified}"),
        _arrow(380, 150, 380, 190),
        _box(230, 190, 300, 70, f"Records screened: {screened}"),
        _arrow(530, 225, 620, 225),
        _box(560, 190, 170, 70, f"Excluded: {excluded}"),
        _arrow(380, 260, 380, 300),
        _box(230, 300, 300, 70, f"Studies included: {included}"),
        _arrow(380, 370, 380, 410),
        _box(230, 410, 300, 70, f"Pending: {pending}"),
        '<text x="30" y="530" fill="#64748b" font-size="12" '
        'font-family="Microsoft YaHei, sans-serif">Generated by SciPal systematic review</text>',
        "</svg>",
    ]
    return "\n".join(parts)
