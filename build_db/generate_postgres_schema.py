#!/usr/bin/env python3
"""Generate a PostgreSQL schema from the SQLite schema (read-only).

The source database is never written. FTS5 shadow tables are skipped; searchable
tables get a generated ``search_vector`` and a GIN index for P1.
"""

from __future__ import annotations

import argparse
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT / "data" / "research.db"
DEFAULT_OUT = ROOT / "build_db" / "postgres_schema.sql"

SEARCH_COLUMNS = {
    "papers": "coalesce(title,'') || ' ' || coalesce(abstract,'')",
    "paragraphs": "coalesce(text,'')",
    "sentences": "coalesce(text,'')",
    "summaries": "coalesce(title,'') || ' ' || coalesce(text,'')",
}


def _type(sql_type: str) -> str:
    upper = (sql_type or "").upper()
    if "INT" in upper:
        return "BIGINT"
    if any(token in upper for token in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE PRECISION"
    if "BLOB" in upper:
        return "BYTEA"
    if any(token in upper for token in ("NUMERIC", "DECIMAL")):
        return "NUMERIC"
    return "TEXT"


def _default(value: str | None, pg_type: str = "TEXT") -> str:
    if value is None:
        return ""
    value = str(value).strip()
    lower = value.lower()
    if lower in {"current_timestamp", "datetime('now')", "date('now')"}:
        if pg_type.upper() == "TEXT":
            return " DEFAULT (CURRENT_TIMESTAMP::text)"
        return " DEFAULT CURRENT_TIMESTAMP"
    if value.upper() == "NULL":
        return " DEFAULT NULL"
    return f" DEFAULT {value}"


def generate(db_path: Path) -> str:
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    rows = conn.execute(
        """
        SELECT name, sql FROM sqlite_master
        WHERE type='table' AND name NOT LIKE 'sqlite_%'
          AND name NOT LIKE '%_fts%'
        ORDER BY name
        """
    ).fetchall()
    lines = [
        "-- Generated from SQLite schema by build_db/generate_postgres_schema.py",
        "-- P1 schema only. No data migration is performed here.",
        "",
    ]
    for name, sql in rows:
        if not sql:
            continue
        columns = conn.execute(f'PRAGMA table_info("{name}")').fetchall()
        ddl_cols = []
        primary = []
        autoincrement = "AUTOINCREMENT" in (sql or "").upper()
        for col in columns:
            cid, col_name, col_type, notnull, default, pk = col
            pg_type = _type(col_type)
            # Citation years contain free-text dates such as "Feb 3, 2020".
            if name == "citations" and col_name == "year":
                pg_type = "TEXT"
            if pk and isinstance(pk, int) and pk > 0:
                primary.append((pk, col_name))
            if pk == 1 and col_name == "id" and "INT" in (col_type or "").upper():
                ddl_cols.append(
                    f'  "{col_name}" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
                )
                continue
            piece = f'  "{col_name}" {pg_type}'
            if notnull:
                piece += " NOT NULL"
            piece += _default(default, pg_type)
            ddl_cols.append(piece)
        if primary and not any("PRIMARY KEY" in col for col in ddl_cols):
            keys = ", ".join(f'"{col}"' for _, col in sorted(primary))
            ddl_cols.append(f"  PRIMARY KEY ({keys})")
        lines.append(f'CREATE TABLE IF NOT EXISTS "{name}" (')
        lines.append(",\n".join(ddl_cols))
        lines.append(");")
        lines.append("")
    for table, expression in SEARCH_COLUMNS.items():
        if not any(f'"{table}"' in line for line in lines):
            continue
        lines.append(
            f'ALTER TABLE "{table}" ADD COLUMN IF NOT EXISTS search_vector tsvector '
            f"GENERATED ALWAYS AS (to_tsvector('english', {expression})) STORED;"
        )
        lines.append(
            f'CREATE INDEX IF NOT EXISTS "{table}_search_idx" ON "{table}" USING GIN (search_vector);'
        )
        lines.append("")
    conn.close()
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=str(DEFAULT_DB))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    text = generate(Path(args.db))
    Path(args.out).write_text(text, encoding="utf-8")
    print({"out": args.out, "tables": text.count("CREATE TABLE"), "bytes": len(text)})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
