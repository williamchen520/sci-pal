-- G3.11: abstracts library in PostgreSQL
CREATE TABLE IF NOT EXISTS abstracts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pmid text UNIQUE,
    doi text,
    title text,
    abstract text,
    authors text,
    journal text,
    year bigint,
    topic text,
    source text DEFAULT 'pubmed_abstract'
);

CREATE INDEX IF NOT EXISTS abstracts_year_idx ON abstracts (year DESC);
