"""Word (.docx) report for a systematic review project."""

from __future__ import annotations

import io
import sqlite3

from docx import Document
from docx.shared import Pt

from services.review import risk_of_bias, systematic


def render_docx(conn: sqlite3.Connection, project_id: str) -> bytes:
    project = systematic.get_project(conn, project_id)
    if not project:
        raise KeyError("project not found")
    counts = systematic.prisma(conn, project_id)
    evidence = systematic.list_evidence(conn, project_id)
    rob_rows = risk_of_bias.list_rows(conn, project_id)

    document = Document()
    style = document.styles["Normal"]
    style.font.name = "Microsoft YaHei"
    style.font.size = Pt(10)

    document.add_heading(project.get("name") or project_id, level=0)
    document.add_paragraph(f"项目：{project_id}")
    document.add_paragraph(f"领域：{project.get('field_text') or '未填写'}")

    document.add_heading("PICO", level=1)
    pico = project.get("pico") or {}
    for key in ("population", "intervention", "comparator", "outcome"):
        document.add_paragraph(f"{key}: {pico.get(key) or '未填写'}", style="List Bullet")

    document.add_heading("PRISMA", level=1)
    table = document.add_table(rows=1, cols=2)
    table.style = "Table Grid"
    table.rows[0].cells[0].text = "指标"
    table.rows[0].cells[1].text = "数量"
    for key in ("identified", "screened", "included", "excluded", "pending"):
        cells = table.add_row().cells
        cells[0].text = key
        cells[1].text = str(counts.get(key, 0))

    document.add_heading("证据表", level=1)
    if evidence:
        table = document.add_table(rows=1, cols=6)
        table.style = "Table Grid"
        headers = ["Paper", "Design", "Sample", "Intervention", "Comparator", "Effect"]
        for index, header in enumerate(headers):
            table.rows[0].cells[index].text = header
        for row in evidence:
            cells = table.add_row().cells
            for index, key in enumerate(
                ("paper_id", "design", "sample_size", "intervention", "comparator", "effect")
            ):
                cells[index].text = str(row.get(key) or "")
    else:
        document.add_paragraph("暂无证据行。")

    document.add_heading("风险偏倚", level=1)
    if rob_rows:
        by_paper = {}
        for row in rob_rows:
            by_paper.setdefault(row["paper_id"], []).append(row)
        table = document.add_table(rows=1, cols=2)
        table.style = "Table Grid"
        table.rows[0].cells[0].text = "Paper"
        table.rows[0].cells[1].text = "Overall"
        for paper, items in by_paper.items():
            cells = table.add_row().cells
            cells[0].text = paper
            cells[1].text = risk_of_bias.overall(items)
    else:
        document.add_paragraph("暂无风险评估。")

    document.add_paragraph("Generated by SciPal systematic review")
    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()
