"""Standalone HTML report for a systematic review project."""

from __future__ import annotations

import html
import sqlite3

from services.review import prisma_svg, risk_of_bias, rob_svg, systematic


def _cell(value: str) -> str:
    return html.escape(str(value or ""))


def render_html(conn: sqlite3.Connection, project_id: str) -> str:
    project = systematic.get_project(conn, project_id)
    if not project:
        raise KeyError("project not found")
    counts = systematic.prisma(conn, project_id)
    evidence = systematic.list_evidence(conn, project_id)
    rob_rows = risk_of_bias.list_rows(conn, project_id)
    pico = project.get("pico") or {}

    rows_html = "".join(
        "<tr>"
        f"<td>{_cell(row.get('paper_id'))}</td>"
        f"<td>{_cell(row.get('design'))}</td>"
        f"<td>{_cell(row.get('sample_size'))}</td>"
        f"<td>{_cell(row.get('intervention'))}</td>"
        f"<td>{_cell(row.get('comparator'))}</td>"
        f"<td>{_cell(row.get('effect'))}</td>"
        "</tr>"
        for row in evidence
    )
    evidence_table = (
        "<table><thead><tr><th>Paper</th><th>Design</th><th>Sample</th>"
        "<th>Intervention</th><th>Comparator</th><th>Effect</th></tr></thead>"
        f"<tbody>{rows_html}</tbody></table>"
        if evidence
        else "<p>暂无证据行。</p>"
    )

    by_paper = {}
    for row in rob_rows:
        by_paper.setdefault(row["paper_id"], []).append(row)
    rob_table = (
        "<table><thead><tr><th>Paper</th><th>Overall</th></tr></thead><tbody>"
        + "".join(
            f"<tr><td>{_cell(paper)}</td><td>{_cell(risk_of_bias.overall(items))}</td></tr>"
            for paper, items in by_paper.items()
        )
        + "</tbody></table>"
        if by_paper
        else "<p>暂无风险评估。</p>"
    )

    prisma_counts = "".join(
        f"<li><b>{_cell(key)}</b>: {counts.get(key, 0)}</li>"
        for key in ("identified", "screened", "included", "excluded", "pending")
    )
    pico_html = "".join(
        f"<li><b>{_cell(key)}</b>: {_cell(pico.get(key) or '未填写')}</li>"
        for key in ("population", "intervention", "comparator", "outcome")
    )

    return f"""<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<title>{_cell(project.get('name'))}</title>
<style>
  body {{ font-family: -apple-system, "Microsoft YaHei", sans-serif; margin: 32px auto; max-width: 960px; color: #0f172a; }}
  h1 {{ border-bottom: 3px solid #0ea5e9; padding-bottom: 8px; }}
  h2 {{ margin-top: 28px; color: #0c4a6e; }}
  table {{ border-collapse: collapse; width: 100%; font-size: 13px; }}
  th, td {{ border: 1px solid #cbd5e1; padding: 6px 8px; text-align: left; vertical-align: top; }}
  th {{ background: #f1f5f9; }}
  .meta {{ color: #475569; }}
  svg {{ max-width: 100%; height: auto; margin: 12px 0; }}
</style>
</head>
<body>
<h1>{_cell(project.get('name'))}</h1>
<p class="meta">项目 {_cell(project_id)} · 领域：{_cell(project.get('field_text'))}</p>

<h2>PICO</h2>
<ul>{pico_html}</ul>

<h2>PRISMA</h2>
<ul>{prisma_counts}</ul>
{prisma_svg.render(project.get('name') or project_id, counts)}

<h2>Evidence table</h2>
{evidence_table}

<h2>Risk of bias</h2>
{rob_table}
{rob_svg.render(rob_rows)}

<hr>
<p class="meta">Generated by SciPal systematic review</p>
</body>
</html>
"""
